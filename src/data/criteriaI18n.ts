/** Returns the criteria in `lang`, falling back to the English source per item
 *  when a language, or a specific line, has no translation yet. `english` is
 *  always the length-of-record source of truth, so the returned array matches
 *  it one-for-one regardless of translation state. */
export function localizeCriteria(id: string, english: string[], lang: CriteriaLangCode): string[] {
  if (lang === "en") return english;
  const translated = criteriaTranslations[id]?.[lang];
  if (!translated) return english;
  return english.map((en, i) => translated[i] ?? en);
}
